import 'dotenv/config';
import 'express-async-errors';
import http from 'node:http';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { Server } from 'socket.io';
import { connectDatabase } from './config/database.js';
import authRoutes from './routes/authRoutes.js';
import attendanceRoutes from './routes/attendanceRoutes.js';
import peopleRoutes from './routes/peopleRoutes.js';
import resourceRoutes from './routes/resourceRoutes.js';
import { errorHandler, notFound } from './middleware/errors.js';
import { startAttendanceScheduler } from './services/absenceService.js';

const app = express();
const server = http.createServer(app);
const io = new Server(server, { cors: { origin: process.env.CLIENT_ORIGIN || 'http://localhost:5173', methods: ['GET', 'POST'] } });
app.set('io', io);
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_ORIGIN || 'http://localhost:5173' }));
app.use(express.json({ limit: '2mb' }));
app.use(morgan(process.env.NODE_ENV === 'production' ? 'combined' : 'dev'));
app.get('/api/health', (req, res) => res.json({ status: 'ok', timestamp: new Date().toISOString() }));
app.use('/api/auth', authRoutes);
app.use('/api/attendance', attendanceRoutes);
app.use('/api', peopleRoutes);
app.use('/api', resourceRoutes);
app.use(notFound);
app.use(errorHandler);
io.on('connection', (socket) => { socket.emit('system:ready', { timestamp: new Date().toISOString() }); });

const port = Number(process.env.PORT || 5000);
connectDatabase().then(() => server.listen(port, () => { startAttendanceScheduler(); console.log(`Navira API listening on :${port}`); })).catch((error) => { console.error('Database connection failed', error); process.exit(1); });
